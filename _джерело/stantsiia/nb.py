# ---------- стрілки: корінь, прямий і боковий напрямки ----------
def leave_dir(ed, node):
    p = ed['p'] if ed['a'] == node else ed['p'][::-1]
    x0, y0 = p[0]
    for x1, y1 in p[1:]:
        if abs(x1 - x0) + abs(y1 - y0) > 6:
            break
    return (x1 - x0, y1 - y0)
SW = {}
for nid in N:
    if not nid.startswith('s'):
        continue
    inc = [ed for ed in E if nid in (ed['a'], ed['b'])]
    if len(inc) != 3:
        raise SystemExit('switch %s has %d edges' % (nid, len(inc)))
    dirs = [(ed, leave_dir(ed, nid)) for ed in inc]
    right = [x for x in dirs if x[1][0] > 0]; left = [x for x in dirs if x[1][0] < 0]
    if len(right) == 1:
        stem, br = right[0], left
    elif len(left) == 1:
        stem, br = left[0], right
    else:
        raise SystemExit('bad switch %s' % nid)
    # прямий напрямок: менший кут до осі колії
    def ang(v): return abs(math.atan2(v[1], abs(v[0])))
    br = sorted(br, key=lambda x: ang(x[1]))
    SW[nid[1:]] = dict(n=nid, st=stem[0]['id'], pl=br[0][0]['id'], mi=br[1][0]['id'])

