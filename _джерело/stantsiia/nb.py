# ---------- розрізання колій у точках світлофорів ----------
def split_at(edge, x):
    p = edge['p']
    for i in range(len(p) - 1):
        (x0, y0), (x1, y1) = p[i], p[i + 1]
        lo, hi = min(x0, x1), max(x0, x1)
        if lo <= x <= hi and x1 != x0:
            t = (x - x0) / (x1 - x0); y = y0 + (y1 - y0) * t
            return p[:i + 1] + [[x, round(y, 1)]], [[x, round(y, 1)]] + p[i + 1:], (x, round(y, 1))
    raise SystemExit('no split %s %s %s' % (edge['a'], edge['b'], x))

