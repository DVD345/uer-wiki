def rdp(pts, eps):
    if len(pts) < 3: return pts
    (x0, y0), (x1, y1) = pts[0], pts[-1]; L = math.hypot(x1 - x0, y1 - y0) or 1
    dm, im = 0, 0
    for i in range(1, len(pts) - 1):
        d = abs((y1 - y0) * pts[i][0] - (x1 - x0) * pts[i][1] + x1 * y0 - y1 * x0) / L
        if d > dm: dm, im = d, i
    if dm > eps: return rdp(pts[:im + 1], eps)[:-1] + rdp(pts[im:], eps)
    return [pts[0], pts[-1]]
def smooth(pts):
    out = [pts[0]]
    for i in range(1, len(pts) - 1):
        w = pts[max(0, i - 3):i + 4]
        out.append((sum(q[0] for q in w) / len(w), sum(q[1] for q in w) / len(w)))
    out.append(pts[-1])
    return rdp(out, 0.7)

