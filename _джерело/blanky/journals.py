from PIL import Image, ImageDraw, ImageFont
INK=(28,48,150)
FP='/usr/share/fonts/truetype/liberation/LiberationSans-Italic.ttf'
def mk(n):
    im=Image.open('/tmp/claude-0/bcrop/%s.png'%n).convert('RGB'); return im, ImageDraw.Draw(im)
def put(d,x0,x1,y0,y1,s,sz,align='l'):
    f=ImageFont.truetype(FP,sz); w=d.textlength(s,font=f)
    while w>x1-x0-8 and sz>11: sz-=1; f=ImageFont.truetype(FP,sz); w=d.textlength(s,font=f)
    x=x0+6 if align=='l' else x0+(x1-x0-w)/2
    d.text((x,y0+(y1-y0-sz)/2-2),s,font=f,fill=INK)

